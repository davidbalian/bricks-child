<?php
/** Move only the disposable local fixture into the administrator-only review boundary. */
if (wp_get_environment_type() !== 'local' || wp_parse_url(home_url('/'), PHP_URL_HOST) !== '127.0.0.1') { WP_CLI::error('Local fixture only.'); }
if (!\AutoAgora\Dealer\Review::admin()) { WP_CLI::error('Run with the local fixture administrator.'); }
$storage = \AutoAgora\Dealer\Review::storage();
if (!$storage || !is_dir(dirname($storage))) { WP_CLI::error('Configure private review storage first.'); }
wp_mkdir_p($storage);
chmod($storage, 0700);
update_option('autoagora_dealer_review_data_exists', 1, true);
global $wpdb;
foreach (['dealer-one-test', 'dealer-two-test', 'private-seller-test'] as $login) {
    $user = get_user_by('login', $login);
    if (!$user) { continue; }
    update_user_meta($user->ID, \AutoAgora\Dealer\Review::USER_META, 1);
    if ($login === 'private-seller-test') { continue; }
    $profiles = $wpdb->get_col($wpdb->prepare("SELECT ID FROM {$wpdb->posts} WHERE post_type='dealer_profile' AND post_author=%d AND post_status<>'trash'", $user->ID));
    if (!$profiles) {
        wp_insert_post(['post_type' => 'dealer_profile', 'post_status' => 'draft', 'post_title' => $user->display_name, 'post_author' => $user->ID,
            'meta_input' => [\AutoAgora\Dealer\Review::META => 1, 'dealer_claimed_user_id' => $user->ID, 'dealer_claim_status' => 'claimed']]);
    }
}
$posts = $wpdb->get_results("SELECT ID,post_status,post_type FROM {$wpdb->posts} WHERE post_type IN ('car','dealer_profile','attachment')");
$publicRoot = WP_CONTENT_DIR . '/uploads';
$moved = 0;
// This fresh fixture has no copied customer uploads; all files here were generated by its tests.
if (is_dir($publicRoot)) {
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($publicRoot, FilesystemIterator::SKIP_DOTS));
    foreach ($files as $file) {
        if (!$file->isFile() || !in_array(strtolower($file->getExtension()), ['jpg', 'jpeg', 'webp', 'png', 'gif'], true)) { continue; }
        $relative = substr($file->getPathname(), strlen($publicRoot) + 1);
        $target = $storage . '/' . $relative;
        wp_mkdir_p(dirname($target));
        if (!is_file($target) && !copy($file->getPathname(), $target)) { WP_CLI::error('Private media copy failed. Original was retained.'); }
        if (hash_file('sha256', $target) !== hash_file('sha256', $file->getPathname())) { WP_CLI::error('Private media verification failed. Original was retained.'); }
        unlink($file->getPathname());
        $moved++;
    }
}
foreach ($posts as $post) {
    update_post_meta($post->ID, \AutoAgora\Dealer\Review::META, 1);
    if ($post->post_type === 'attachment') {
        $raw = get_post_meta($post->ID, '_wp_attached_file', true);
        if (is_string($raw) && $raw !== '') {
            $relative = str_starts_with($raw, $publicRoot . '/') ? substr($raw, strlen($publicRoot) + 1) : ($raw[0] !== '/' ? $raw : null);
            if ($relative !== null && is_file($storage . '/' . $relative)) { update_post_meta($post->ID, '_wp_attached_file', $storage . '/' . $relative); }
        }
    } elseif (in_array($post->post_status, ['publish', 'future'], true)) { wp_update_post(['ID' => $post->ID, 'post_status' => 'private']); }
    clean_post_cache($post->ID);
}
WP_CLI::success('Local fixture fenced for administrators; ' . count($posts) . ' private records, ' . $moved . ' image files moved outside the web root.');
